/**
 * emojiData — bundled emoji dataset for the Emoji picker tool.
 *
 * This module is dynamically imported by `useEmojiPicker` so Vite emits it as
 * a separate chunk (~180 KB), keeping it out of the initial app shell bundle.
 *
 * Compact schema (per entry):
 *   {
 *     e: string        // the emoji glyph
 *     n: string        // canonical name (lowercase, space-separated)
 *     s: string[]      // shortcodes (without colons), e.g. ['smile','happy']
 *     k?: string[]     // extra search keywords
 *     t?: boolean      // supports skin-tone modifiers (people emojis)
 *   }
 *
 * Categories (in display order):
 *   smileys, people, animals, food, activities, travel, objects, symbols, flags
 *
 * No external dependencies — the dataset is hand-curated from the Unicode CLDR
 * short names and common shortcode conventions.
 */

/* -------------------------------------------------------------------------- */
/* Types                                                                       */
/* -------------------------------------------------------------------------- */

export interface EmojiEntry {
  /** The emoji glyph (one or more Unicode code points). */
  e: string;
  /** Canonical name, lowercase, space-separated. */
  n: string;
  /** Shortcodes without surrounding colons, e.g. `['smile', 'happy']`. */
  s: string[];
  /** Optional extra search keywords. */
  k?: string[];
  /** When true, the emoji supports skin-tone modifiers (U+1F3FB–U+1F3FF). */
  t?: boolean;
}

export type EmojiCategory =
  | 'smileys'
  | 'people'
  | 'animals'
  | 'food'
  | 'activities'
  | 'travel'
  | 'objects'
  | 'symbols'
  | 'flags';

export interface EmojiCategoryData {
  /** Category identifier. */
  id: EmojiCategory;
  /** Human-readable label. */
  label: string;
  /** Emoji entries for this category. */
  emojis: EmojiEntry[];
}

/* -------------------------------------------------------------------------- */
/* Skin tones — U+1F3FB (light) … U+1F3FF (dark)                              */
/* -------------------------------------------------------------------------- */

export interface SkinTone {
  /** Tone identifier. */
  id: 'none' | 'light' | 'medium-light' | 'medium' | 'medium-dark' | 'dark';
  /** Human-readable label. */
  label: string;
  /** The Fitzpatrick modifier code point, or empty string for `none`. */
  modifier: string;
  /** A representative swatch glyph (a hand emoji with the tone applied). */
  swatch: string;
}

