/**
 * ports.ts - bundled well-known port reference data for the PortReference
 * tool.
 *
 * A curated subset of the IANA Service Name and Transport Protocol Port
 * Number Registry covering the most commonly referenced ports (system ports
 * 0-1023 plus frequently used registered ports). `protocol` is `'tcp'`,
 * `'udp'`, or `'both'` when the port is assigned to both transports.
 *
 * No external dependencies - this file is bundled with the tool chunk.
 */

/** A single port → service assignment. */
export interface PortEntry {
  /** Port number (0-65535). */
  port: number;
  /** Transport protocol assignment. */
  protocol: 'tcp' | 'udp' | 'both';
  /** IANA service name / keyword. */
  service: string;
  /** Short human-readable description. */
  description: string;
}

